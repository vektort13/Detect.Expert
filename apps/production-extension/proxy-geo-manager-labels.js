// One frozen table per language; a language that lacks a key reads the English one (adding a language is a data change).
const build = table => Object.freeze(Object.fromEntries(GEO_MANAGER_LABEL_KEYS.map(key => [key, typeof table?.[key] === 'string' && table[key] !== '' ? table[key] : rows.en[key]])));
export const GEO_MANAGER_LABELS = Object.freeze(Object.fromEntries(Object.entries(rows).map(([locale, table]) => [locale, build(table)])));
const own = id => (Object.hasOwn(GEO_MANAGER_LABELS, id) ? GEO_MANAGER_LABELS[id] : undefined);
/** The labels of one language: a locale id or { id }; a variant (pt-BR, de-AT) falls back to its language and everything else to English. */
export function proxyGeoManagerLabels(locale) {
  const key = typeof locale === 'string' ? locale : typeof locale?.id === 'string' ? locale.id : 'en';
  return own(key) ?? own(key.replace('-', '_')) ?? own(key.split(/[-_]/u)[0]) ?? GEO_MANAGER_LABELS.en;
}
