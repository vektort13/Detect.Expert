export type ApiOperation = typeof API_OPERATION_DEFINITIONS[number][0];
export type ApiMechanism = typeof API_OPERATION_DEFINITIONS[number][2];
export type ApiOperationKind = typeof API_OPERATION_DEFINITIONS[number][3];
export const API_OPERATIONS: readonly ApiOperation[] = Object.freeze(API_OPERATION_DEFINITIONS.map(definition => definition[0]));
export const API_MECHANISMS = ['webgpu', 'wasm', 'client-hints', 'window-management', 'compute-pressure', 'idle-detection', 'audio', 'webnn',
  'media-capabilities', 'media-devices', 'speech', 'drm', 'device-access', 'browser-capabilities', 'builtin-ai', 'recognition', 'app-integration', 'webrtc'] as const;

export interface ApiOperationDefinition {
  readonly techniqueId: TechniqueId;
  readonly mechanism: ApiMechanism;
  readonly kind: ApiOperationKind;
}

const apply = Reflect.apply;
const mapGet = Map.prototype.get;
const definitions = new Map<string, ApiOperationDefinition>(API_OPERATION_DEFINITIONS.map(([operation, techniqueId, mechanism, kind]) =>
  [operation, Object.freeze({ techniqueId, mechanism, kind })]));

export function apiOperationDefinition(operation: unknown): ApiOperationDefinition | null {
  if (typeof operation !== 'string' || operation.length > 64) return null;
  return apply(mapGet, definitions, [operation]) as ApiOperationDefinition | undefined ?? null;
}

export function isApiOperation(operation: unknown): operation is ApiOperation {
  return apiOperationDefinition(operation) !== null;
}

export function apiOperationAllows(operation: unknown, techniqueId: TechniqueId, phase: Phase): boolean {
  const definition = apiOperationDefinition(operation);
  return definition !== null && definition.techniqueId === techniqueId &&
    (phase === 'threw-sync' || phase === (definition.kind === 'async-call' ? 'settlement-unobserved' : 'returned-sync'));
}

export interface ApiOperationSummary {
  apiOperation: ApiOperation;
  phase: Phase;
  count: number;
  countQuality: CountQuality;
}

export function readApiOperations(value: unknown): ApiOperationSummary[] | null {
  try {
    if (!Array.isArray(value) || Object.getPrototypeOf(value) !== Array.prototype ||
        value.length > BUDGETS.maxCountersPerDocumentGroup || Reflect.ownKeys(value).length !== value.length + 1) return null;
    const out: ApiOperationSummary[] = [], seen = new Set<string>();
    const keys = ['apiOperation', 'phase', 'count', 'countQuality'] as const;
    for (let index = 0; index < value.length; index++) {
      const item = Object.getOwnPropertyDescriptor(value, String(index));
      if (!item || !Object.hasOwn(item, 'value')) return null;
      const row: unknown = item.value;
      if (typeof row !== 'object' || row === null || Array.isArray(row) || Reflect.ownKeys(row).length !== keys.length) return null;
      const prototype: unknown = Object.getPrototypeOf(row);
      if (prototype !== Object.prototype && prototype !== null) return null;
      const fields: unknown[] = [];
      for (const key of keys) {
        const field = Object.getOwnPropertyDescriptor(row, key);
        if (!field || !field.enumerable || !Object.hasOwn(field, 'value')) return null;
        fields.push(field.value);
      }
      const [apiOperation, phase, count, countQuality] = fields;
      const definition = apiOperationDefinition(apiOperation);
      if (definition === null || !PHASES.includes(phase as Phase) || !COUNT_QUALITIES.includes(countQuality as CountQuality) ||
          !apiOperationAllows(apiOperation, definition.techniqueId, phase as Phase) ||
          typeof count !== 'number' || !Number.isInteger(count) || count < 1 || count > MAX_COUNT) return null;
      const key = String(apiOperation) + '|' + String(phase);
      if (seen.has(key)) return null;
      seen.add(key);
      out.push({ apiOperation: apiOperation as ApiOperation, phase: phase as Phase, count, countQuality: countQuality as CountQuality });
    }
    return out;
  } catch { return null; }
}
