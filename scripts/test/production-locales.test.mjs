test('production locales: generation is repeatable and preserves unrelated runtime sections', () => {
  const temporary = resolve('.tmp');
  mkdirSync(temporary, { recursive: true });
  const copy = mkdtempSync(join(temporary, 'locales-idempotence-'));
  const runtime = ['popup.js', 'sidepanel.js', 'options.js', 'report.js', 'background.js'];
  const files = [...runtime];
  try {
    for (const name of runtime) cpSync(resolve(directory, name), resolve(copy, name));
    for (const language of PRODUCTION_LANGUAGES) {
      const name = join(language.uiOnly ? 'ui-locales' : '_locales', language.id, 'messages.json');
      mkdirSync(resolve(copy, language.uiOnly ? 'ui-locales' : '_locales', language.id), { recursive: true });
      cpSync(resolve(directory, name), resolve(copy, name));
      files.push(name);
    }
    const sentinel = '\n// Unrelated Pro runtime section remains byte-for-byte intact.\n';
    for (const name of runtime) writeFileSync(resolve(copy, name), readFileSync(resolve(copy, name), 'utf8') + sentinel);
    updateProductionLocales(copy);
    const hashes = files.map(name => createHash('sha256').update(readFileSync(resolve(copy, name))).digest('hex'));
    updateProductionLocales(copy);
    assert.deepEqual(files.map(name => createHash('sha256').update(readFileSync(resolve(copy, name))).digest('hex')), hashes);
    for (const name of runtime) assert.ok(readFileSync(resolve(copy, name), 'utf8').endsWith(sentinel), name);
  } finally {
    assert.ok(copy.startsWith(temporary + sep));
    rmSync(copy, { recursive: true, force: true });
  }
});

test('production locales: Pro disclosures permit selected values and preserve image exclusions', () => {
  for (const language of PRODUCTION_LANGUAGES) {
    assert.match(tables[language.id].api_results_note.message, /Pro/);
    assert.match(tables[language.id].consent_previews.message, /Pro\/PDF/);
    assert.doesNotMatch(tables[language.id].pro_limits_note.message, /WebRTC/, language.id + ': obsolete blanket RTC exclusion');
    for (const key of ['consent_controls', 'consent_previews', 'inventory_sync']) assert.doesNotMatch(tables[language.id][key].message, /Chrome/, language.id + ':' + key + ': shared browser instruction');
  }
  assert.match(tables.en.api_results_note.message, /selected technical parameters and distinct returned values/);
  assert.match(tables.ru.api_results_note.message, /разные возвращённые значения/);
  for (const key of ['rtc_values_scope', 'api_note_webgpu', 'api_note_idle_detection', 'inspector_cpu_desc', 'inspector_memory_desc']) assert.match(tables.en[key].message, /Pro recording/);
  assert.doesNotMatch(tables.en.api_note_audio.message, /parameter values and hashes are not retained/);
  assert.doesNotMatch(tables.en.api_note_wasm.message, /bytes, results/);
  assert.doesNotMatch(tables.en.consent_previews.message, /certificate previews stay/);
  assert.match(tables.en.consent_previews.message, /Images, Google headers stay in bounded memory/);
});
