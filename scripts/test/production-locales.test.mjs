for (const name of ['popup.js', 'sidepanel.js', 'options.js', 'report.js']) {
  test(`production locales: ${name} serves all catalogs and restores language choices`, async () => {
    const source = await readFile(resolve(directory, name), 'utf8');
    const start = source.indexOf('// apps/production-extension/locales — generated by scripts/production-locales.mjs');
    const i18n = source.indexOf('// packages/ui/src/i18n.ts', start);
    const end = source.indexOf('\n// ', i18n + 1);
    assert.ok(start >= 0 && i18n > start && end > i18n, 'generated locale boundary');
    let storageListener;
    const document = { documentElement: {} };
    const context = vm.createContext({
      Intl, Set, document, setTimeout, clearTimeout,
      chrome: {
        i18n: { getUILanguage: () => 'de-CH', getMessage: () => '' },
        storage: {
          onChanged: { addListener(listener) { storageListener = listener; } },
          local: {
            async get() { return { 'ui-language-v1': 'yue' }; },
            async set(values) { storageListener({ 'ui-language-v1': { newValue: values['ui-language-v1'] } }, 'local'); },
          },
        },
      },
    });
    vm.runInContext(source.slice(start, end), context);
    const api = vm.runInContext('({LANGUAGES, TABLES, matchLocale, uiLocale, initializeLanguage, setUiLocale, translate: t3})', context);
    assert.equal(api.LANGUAGES.length, PRODUCTION_LANGUAGES.length);
    for (const language of PRODUCTION_LANGUAGES) assert.deepEqual(JSON.parse(JSON.stringify(api.TABLES[language.id])), tables[language.id], `${name}:${language.id}: embedded catalog differs`);
    for (const [input, expected] of [['de-CH', 'de'], ['pl-PL', 'pl'], ['id-ID', 'id'], ['mr-IN', 'mr'], ['te-IN', 'te'], ['ta-LK', 'ta'], ['ko-KR', 'ko'], ['zh-CN', 'zh_CN'], ['cmn-CN', 'zh_CN'], ['yue-HK', 'yue'], ['wuu-CN', 'wuu']]) assert.equal(api.matchLocale(input), expected);
    await api.initializeLanguage();
    assert.equal(api.uiLocale(), 'yue');
    assert.equal(document.documentElement.lang, 'yue-Hans');
    for (const language of PRODUCTION_LANGUAGES) {
      assert.equal(await api.setUiLocale(language.id), true);
      assert.equal(api.uiLocale(), language.id);
      assert.equal(api.translate('language_label'), tables[language.id].language_label.message);
      assert.equal(api.translate('pro_graph_title'), tables[language.id].pro_graph_title.message);
      assert.equal(api.translate('pro_graph_page', ['3']), tables[language.id].pro_graph_page.message.replace('$NUMBER$', '3'));
      assert.equal(api.translate('pro_graph_omitted', ['2', '4', '8']), tables[language.id].pro_graph_omitted.message.replace('$PAGES$', '2').replace('$DOMAINS$', '4').replace('$EDGES$', '8'));
      assert.equal(document.documentElement.lang, language.tag);
      assert.equal(document.documentElement.dir, language.id === 'ar' || language.id === 'ur' ? 'rtl' : 'ltr');
    }
    assert.equal(await api.setUiLocale('invalid-locale'), false);
  });
}

