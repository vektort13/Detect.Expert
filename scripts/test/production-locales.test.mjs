import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve, sep } from 'node:path';
import vm from 'node:vm';
import { EXTENSION_NAME, PRODUCTION_LANGUAGES } from '../production-languages.mjs';
import { updateProductionLocales } from '../production-locales.mjs';

const directory = resolve('apps/production-extension');
const reference = JSON.parse(await readFile(resolve(directory, '_locales/en/messages.json'), 'utf8'));
const tables = {};
for (const language of PRODUCTION_LANGUAGES) {
  tables[language.id] = JSON.parse(await readFile(resolve(directory, language.uiOnly ? 'ui-locales' : '_locales', language.id, 'messages.json'), 'utf8'));
}
const placeholders = (message) => [...message.matchAll(/\$\$|\$[a-z_][a-z0-9_]*\$|\$[1-9]/gi)].map((match) => match[0].toLowerCase()).sort();

test('production locales: all 21 catalogs have exact keys, metadata and substitutions', () => {
  for (const language of PRODUCTION_LANGUAGES) {
    const table = tables[language.id];
    assert.deepEqual(Object.keys(table).sort(), Object.keys(reference).sort(), language.id);
    assert.equal(table.extName.message, EXTENSION_NAME, language.id);
    assert.ok(Array.from(table.extName.message).length <= 75, `${language.id}: Chrome manifest name limit`);
    assert.ok(Array.from(table.extDescription.message).length <= 132, `${language.id}: Chrome manifest description limit`);
    for (const [key, entry] of Object.entries(table)) {
      assert.equal(typeof entry.message, 'string', `${language.id}:${key}`);
      assert.ok(entry.message.trim(), `${language.id}:${key}`);
      assert.equal(/[\uFFFD\uE000-\uE00F]/u.test(entry.message), false, `${language.id}:${key}: encoding/glossary artifact`);
      assert.deepEqual(placeholders(entry.message), placeholders(reference[key].message), `${language.id}:${key}: substitutions`);
      const { message: _translated, ...metadata } = entry;
      const { message: _original, ...expectedMetadata } = reference[key];
      assert.deepEqual(metadata, expectedMetadata, `${language.id}:${key}: metadata`);
    }
  }
});

test('production locales: new catalogs translate human-readable paragraphs and retain native scripts', () => {
  for (const locale of ['de', 'pl', 'id', 'mr', 'te', 'ko', 'ta', 'yue', 'wuu']) {
    const table = tables[locale];
    for (const [key, entry] of Object.entries(reference)) {
      if (/[A-Za-z]/.test(entry.message) && entry.message.length >= 75) assert.notEqual(table[key].message, entry.message, `${locale}:${key}: English paragraph copied`);
    }
  }
  for (const [locale, script] of [['mr', /[\u0900-\u097F]/u], ['te', /[\u0C00-\u0C7F]/u], ['ta', /[\u0B80-\u0BFF]/u], ['ko', /[\uAC00-\uD7AF]/u], ['yue', /[\u4E00-\u9FFF]/u], ['wuu', /[\u4E00-\u9FFF]/u]]) {
    for (const key of ['consent_intro', 'language_label', 'api_results_note', 'report_print_hint']) assert.ok(script.test(tables[locale][key].message), `${locale}:${key}: native script`);
  }
  assert.match(tables.yue.api_results_note.message, /嘅.*唔同/);
  assert.match(tables.wuu.api_results_note.message, /勒浪.*辰光/);
});

