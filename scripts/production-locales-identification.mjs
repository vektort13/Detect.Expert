export function applyIdentificationCopy(table, locale) {
  if (typeof locale !== 'string' || !Object.hasOwn(COPY, locale)) {
    throw new Error('Identification copy: unknown locale ' + String(locale));
  }
  if (!table || typeof table !== 'object' || Array.isArray(table)) {
    throw new TypeError('Identification copy: expected a message table');
  }
  const copy = COPY[locale];
  if (copy.length !== KEYS.length || copy.some((message) => typeof message !== 'string' || !message)) {
    throw new Error('Identification copy: incomplete translations for ' + locale);
  }
  for (let index = 0; index < KEYS.length; index++) {
    table[KEYS[index]] = { message: copy[index] };
  }
  if (DETAILS[locale].length !== DETAIL_KEYS.length) throw new Error('Cookie details: incomplete translations for ' + locale);
  for (let index = 0; index < DETAIL_KEYS.length; index++) table[DETAIL_KEYS[index]] = { message: DETAILS[locale][index] };
  if (LINKS[locale].length !== LINK_KEYS.length) throw new Error('Tag Manager copy: incomplete translations for ' + locale);
  for (let index = 0; index < LINK_KEYS.length; index++) table[LINK_KEYS[index]] = { message: LINKS[locale][index] };
  if (typeof LOADING_SUMMARY[locale] !== 'string' || !LOADING_SUMMARY[locale].includes('$SERVICES$')) throw new Error('Tag Manager summary: incomplete translation for ' + locale);
  table.tag_manager_loading_summary = { message: LOADING_SUMMARY[locale], placeholders: { services: { content: '$1' } } };
  if (COOKIE_UI[locale].length !== COOKIE_UI_KEYS.length || COOKIE_UI[locale].some(message => typeof message !== 'string' || !message)) throw new Error('Cookie UI: incomplete translations for ' + locale);
  for (let index = 0; index < COOKIE_UI_KEYS.length; index++) table[COOKIE_UI_KEYS[index]] = { message: COOKIE_UI[locale][index] };
  if (COOKIE_VALUES[locale].length !== COOKIE_VALUE_KEYS.length || COOKIE_VALUES[locale].some(message => typeof message !== 'string' || !message)) throw new Error('Cookie values: incomplete translations for ' + locale);
  for (let index = 0; index < COOKIE_VALUE_KEYS.length; index++) table[COOKIE_VALUE_KEYS[index]] = { message: COOKIE_VALUES[locale][index] };
  if (typeof COOKIE_NAME_REFERENCE[locale] !== 'string' || !COOKIE_NAME_REFERENCE[locale]) throw new Error('Cookie name reference: incomplete translation for ' + locale);
  table.cookie_name_reference = { message: COOKIE_NAME_REFERENCE[locale] };
  for (const key of ['cookie_tab_total', 'cookie_total_count', 'cookie_site_count', 'cookie_other_count']) table[key].placeholders = { count: { content: '$1' } };
  table.cookie_clear_result.placeholders = { removed: { content: '$1' }, failed: { content: '$2' } };
  if (!Object.hasOwn(THIRD_PARTY_LABEL, locale) || typeof THIRD_PARTY_LABEL[locale] !== 'string' || !THIRD_PARTY_LABEL[locale]) throw new Error('Third Party label: incomplete translation for ' + locale);
  table.identification_third_party = { message: THIRD_PARTY_LABEL[locale] };
  table.identification_cookie = { message: 'Cookie' };
  table.identification_technique_count.placeholders = { count: { content: '$1' } };
  table.cookie_tracking_count.placeholders = { count: { content: '$1' } };
  return table;
}
