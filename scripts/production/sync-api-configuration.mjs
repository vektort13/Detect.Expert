// ADR-048: deterministic configuration contract mirror, MAIN bundle and narrow production integration.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { build } from 'esbuild';
import { syncApiCustomOpaque } from './sync-api-custom-opaque.mjs';

const root = resolve(import.meta.dirname, '../..'), directory = resolve(root, 'apps/production-extension');
const check = process.argv.includes('--check');
await syncApiCustomOpaque({ check });
function store(path, source) {
  const before = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (before === source) return;
  if (check) throw new Error('API configuration synchronization required: ' + path);
  writeFileSync(path, source, 'utf8');
}
function one(source, before, after, label) {
  if (source.includes(after)) return source;
  if (source.split(before).length !== 2) throw new Error('Missing or ambiguous API configuration integration: ' + label);
  return source.replace(before, after);
}
const features = readFileSync(resolve(root, 'packages/contracts/src/protection-features.mjs'), 'utf8');
const canonical = readFileSync(resolve(root, 'packages/contracts/src/api-configuration.mjs'), 'utf8');
store(resolve(directory, 'webassembly-apis.js'), readFileSync(resolve(root, 'packages/contracts/src/webassembly-apis.mjs'), 'utf8'));
store(resolve(directory, 'math-functions.js'), readFileSync(resolve(root, 'packages/contracts/src/math-functions.mjs'), 'utf8'));
store(resolve(directory, 'fingerprint-custom-values.js'), readFileSync(resolve(root, 'packages/contracts/src/fingerprint-custom-values.mjs'), 'utf8'));
const browserImports = source => source.replaceAll("from './protection-features.mjs'", "from './api-protection-features.js'").replaceAll("from './webassembly-apis.mjs'", "from './webassembly-apis.js'").replaceAll("from './math-functions.mjs'", "from './math-functions.js'").replaceAll("from './fingerprint-custom-values.mjs'", "from './fingerprint-custom-values.js'");
store(resolve(directory, 'api-protection-features.js'), browserImports(features));
store(resolve(directory, 'api-configuration.js'), browserImports(canonical));
const bundled = await build({ entryPoints: [resolve(directory, 'api-custom-main.entry.js')], bundle: true, write: false,
  format: 'iife', target: 'chrome119', platform: 'browser', minify: false, legalComments: 'none', logLevel: 'silent' });
store(resolve(directory, 'api-custom.main.js'), '// ADR-048: generated by sync-api-configuration.mjs.\n' + bundled.outputFiles[0].text);

let background = readFileSync(resolve(directory, 'background.js'), 'utf8');
const proxyImports = 'import { installProxyService } from "./proxy-service.js";\nimport { createProxyPrivacyOverlay } from "./proxy-privacy.js";\n';
background = background.replace(proxyImports, '');
background = background.replaceAll('import { ApiConfigurationController } from "./api-configuration-controller.js";\n', '');
background = one(background, 'import { protectHost, isProtectSessionKey } from "./protect-sw.js";\n',
  'import { protectHost, isProtectSessionKey } from "./protect-sw.js";\nimport { ApiConfigurationController } from "./api-configuration-controller.js";\n', 'controller import');
const proxyImportAnchor = background.includes('import { createVendorRedirectTracker } from "./vendor-redirects.js";\n') ? 'import { createVendorRedirectTracker } from "./vendor-redirects.js";\n' : 'import { ApiConfigurationController } from "./api-configuration-controller.js";\n';
background = background.replace(proxyImportAnchor, proxyImportAnchor + proxyImports);
background = one(background, 'async function route(runtime, message, sender) {\n',
  'async function route(runtime, message, sender) {\n  // ADR-048: existing trusted sender checks are passed unchanged to the configuration controller.\n  const apiConfigurationRoute = runtime.apiConfiguration?.route(message, sender);\n  if (apiConfigurationRoute !== null && apiConfigurationRoute !== undefined) return apiConfigurationRoute;\n', 'message route');
background = one(background, 'new ProtectionController(api, this.scope, () => this.badge.markAll())',
  'new ProtectionController(api, this.scope, () => { this.badge.markAll(); this.apiConfiguration?.legacyChanged(); })', 'legacy changes');
// ADR-064: one owner for these protocols. A legacy closure with a public stop
// listener must never capture constructors before the closed early installer.
background = one(background,
  'let desired = buildProtectionScripts(this.settings, this.accessUnavailable || !this.scope.accessReady ? [] : this.scope.desiredMatches());',
  'let desired = buildProtectionScripts(this.settings, this.accessUnavailable || !this.scope.accessReady ? [] : this.scope.desiredMatches()).filter(script => !["detector-protection-v1-webrtc", "detector-protection-v1-websocket", "detector-protection-v1-webtransport"].includes(script.id));',
  'exclusive early protocol ownership');
const begin = '// ADR-048 API configuration integration start\n', end = '// ADR-048 API configuration integration end\n';
const integration = begin + `background.runtime.apiConfiguration = new ApiConfigurationController({
  api: chrome, legacy: background.runtime.protection, scope: background.runtime.scope,
  whenReady: () => background.runtime.whenReady(), verifyUiSender, readPageSender
});
background.runtime.proxy = installProxyService(chrome, { privacyOverlay: createProxyPrivacyOverlay(chrome, background.runtime.apiConfiguration) });
void background.runtime.proxy.ready.finally(() => background.runtime.apiConfiguration.start()).catch(() => {});
chrome.permissions.onAdded.addListener(() => background.runtime.apiConfiguration.legacyChanged());
chrome.permissions.onRemoved.addListener(() => background.runtime.apiConfiguration.legacyChanged());
chrome.tabs.onRemoved.addListener(tabId => background.runtime.apiConfiguration.removed(tabId));
` + end;
if (background.includes(begin)) {
  const first = background.indexOf(begin), last = background.indexOf(end, first);
  if (last < first || background.indexOf(begin, first + begin.length) >= 0) throw new Error('Invalid API integration markers');
  background = background.slice(0, first) + integration + background.slice(last + end.length);
} else background = one(background, 'background.start();\n', integration + 'background.start();\n', 'controller startup');
store(resolve(directory, 'background.js'), background);

let ui = readFileSync(resolve(directory, 'protection-ui.js'), 'utf8');
const dependency = 'import { createApiConfigurationUi } from "./api-configuration-ui.js";\n';
if (!ui.startsWith(dependency)) ui = dependency + ui;
ui = ui.replace('createApiConfigurationUi({ h, useState, useEffect, useRef, useLocale, browserApi })', 'createApiConfigurationUi({ h, useState, useEffect, useRef, useLocale, browserApi, translate, featureFilter: PROTECTION_FEATURE_FILTER })');
const configurationFactory = `createApiConfigurationUi({ h, useState, useEffect, useRef, useLocale, browserApi, translate, featureFilter: PROTECTION_FEATURE_FILTER, renderGroupIcon: id => {
    const group = PROTECTION_GROUPS.find(group => group.id === id);
    return group ? icon(group.icon, 'blocking-group__icon') : null;
  } })`;
ui = ui.replace('createApiConfigurationUi({ h, useState, useEffect, useRef, useLocale, browserApi, translate, featureFilter: PROTECTION_FEATURE_FILTER })', configurationFactory);
ui = one(ui, 'PROTECTION_FEATURES, MAX_PROTECTION_SITES, readProtectionSettings, readProtectionObservations, isProtectionHost, effectiveProtection }) {',
  'PROTECTION_FEATURES, MAX_PROTECTION_SITES, readProtectionSettings, readProtectionObservations, isProtectionHost, effectiveProtection, apiConfigurationEnabled = false }) {', 'UI option');
ui = one(ui, '  return { ProtectionLauncher, ProtectionSettings };\n',
  '  const configurationUi = apiConfigurationEnabled ? ' + configurationFactory + ' : null;\n  return { ProtectionLauncher, ProtectionSettings: configurationUi ? configurationUi.ApiConfigurationEditor : ProtectionSettings };\n', 'unified editor');
store(resolve(directory, 'protection-ui.js'), ui);
for (const name of ['options.html', 'popup.html', 'sidepanel.html', 'protection.html']) {
  let html = readFileSync(resolve(directory, name), 'utf8');
  if (!html.includes('href="api-configuration-ui.css"')) html = one(html, 'href="protection-ui.css" />', 'href="protection-ui.css" />\n    <link rel="stylesheet" href="api-configuration-ui.css" />', name + ' styles');
  if (!html.includes('href="webrtc-configuration-ui.css"')) html = one(html, 'href="api-configuration-ui.css" />', 'href="api-configuration-ui.css" />\n    <link rel="stylesheet" href="webrtc-configuration-ui.css" />', name + ' WebRTC styles');
  store(resolve(directory, name), html);
}
console.log('API configuration: canonical contract, MAIN bundle and production integration synchronized' + (check ? ' (check)' : ''));
