// ADR-049: one deterministic packaged opaque-realm guard per supported API.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { API_CONFIG_CATALOG } from '../../packages/contracts/src/api-configuration.mjs';
import { FINGERPRINT_CUSTOM_ENTRIES } from '../../packages/contracts/src/fingerprint-custom-values.mjs';
import { API_CUSTOM_OPAQUE_NEUTRALS } from '../../apps/production-extension/api-custom-opaque.entry.js';

const root = resolve(import.meta.dirname, '../..');
export const API_CUSTOM_OPAQUE_IDS = Object.freeze(API_CONFIG_CATALOG.filter(entry => entry.customSupported).map(entry => entry.id));
export const apiCustomOpaqueFile = id => {
  if (!API_CUSTOM_OPAQUE_IDS.includes(id)) throw new TypeError('Unknown opaque API guard.');
  return 'api-custom-opaque.' + id + '.js';
};
export async function syncApiCustomOpaque({ check = false, directory = resolve(root, 'apps/production-extension') } = {}) {
  // The small enum is also needed when synchronizing opaque bundles by themselves.
  const mathFunctions = readFileSync(resolve(root, 'packages/contracts/src/math-functions.mjs'), 'utf8'), mathPath = resolve(directory, 'math-functions.js');
  if (!existsSync(mathPath) || readFileSync(mathPath, 'utf8') !== mathFunctions) {
    if (check) throw new Error('Math enum synchronization required.');
    writeFileSync(mathPath, mathFunctions, 'utf8');
  }
  const mapped = Object.keys(API_CUSTOM_OPAQUE_NEUTRALS).sort(), expected = [...API_CUSTOM_OPAQUE_IDS].sort();
  if (JSON.stringify(mapped) !== JSON.stringify(expected)) throw new Error('Opaque API withholding states must cover the complete Custom catalogue.');
  const outputs = [];
  for (const id of API_CUSTOM_OPAQUE_IDS) {
    const extended = FINGERPRINT_CUSTOM_ENTRIES.some(entry => entry.id === id);
    const result = await build({ entryPoints: [resolve(root, 'apps/production-extension/' + (extended ? 'api-custom-extended-opaque.entry.js' : id === 'media-capabilities' ? 'api-custom-media-opaque.entry.js' : id === 'webrtc' ? 'api-custom-webrtc-opaque.entry.js' : id === 'math-transcendentals' ? 'api-custom-math-opaque.entry.js' : id === 'canvas-readback' ? 'api-custom-canvas-opaque.entry.js' : id === 'geolocation' ? 'api-custom-geolocation-opaque.entry.js' : 'api-custom-opaque.entry.js'))], bundle: true, write: false,
      format: 'iife', target: 'chrome119', platform: 'browser', minify: false, legalComments: 'none', logLevel: 'silent',
      define: { __DETECT_EXPERT_OPAQUE_API_ID__: JSON.stringify(id) } });
    const source = '// ADR-049: generated by sync-api-custom-opaque.mjs; native metadata is withheld in opaque inherited realms.\n' + result.outputFiles[0].text;
    const name = apiCustomOpaqueFile(id), path = resolve(directory, name);
    const previous = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (previous !== source) {
      if (check) throw new Error('Opaque API guard synchronization required: ' + name);
      writeFileSync(path, source, 'utf8');
    }
    outputs.push({ id, file: name, bytes: Buffer.byteLength(source) });
  }
  for (const id of ['webrtc', 'websocket', 'webtransport']) {
    const result = await build({ entryPoints: [resolve(root, 'apps/production-extension/antidetect-block-opaque.entry.js')], bundle: true, write: false,
      format: 'iife', target: 'chrome119', platform: 'browser', minify: false, legalComments: 'none', logLevel: 'silent',
      define: { __DETECT_EXPERT_BLOCK_API_ID__: JSON.stringify(id) } });
    const source = '// ADR-064: generated document-start opaque protocol guard.\n' + result.outputFiles[0].text;
    const name = 'antidetect-block-opaque.' + id + '.js', path = resolve(directory, name);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== source) {
      if (check) throw new Error('Opaque protocol guard synchronization required: ' + name);
      writeFileSync(path, source, 'utf8');
    }
    outputs.push({ id, file: name, bytes: Buffer.byteLength(source) });
  }
  return outputs;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const check = process.argv.includes('--check'), outputs = await syncApiCustomOpaque({ check });
  console.log(`Opaque API guards: ${outputs.length} files, ${outputs.reduce((sum, entry) => sum + entry.bytes, 0)} bytes synchronized${check ? ' (check)' : ''}`);
}
