import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '../..');
export async function syncCookieSite({ check = false } = {}) {
  const file = resolve(root, 'apps/production-extension/cookie-site.js');
  const result = await build({ entryPoints: [resolve(import.meta.dirname, 'cookie-site-entry.ts')], bundle: true, treeShaking: true,
    format: 'esm', platform: 'browser', target: 'es2022', write: false, legalComments: 'none', logLevel: 'silent' });
  const source = '// Generated by scripts/production/sync-cookie-site.mjs from the pinned offline PSL; do not edit.\n' + result.outputFiles[0].text;
  if (!existsSync(file) || readFileSync(file, 'utf8') !== source) {
    if (check) throw Error('Cookie site synchronization required.');
    writeFileSync(file, source, 'utf8');
  }
  return file;
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await syncCookieSite({ check: process.argv.includes('--check') }); console.log('Cookie site synchronized' + (process.argv.includes('--check') ? ' (check)' : ''));
}
