/** @detect-expert/<pkg>[/<sub>] -> vendored source file, from the vendored package.json exports. */
function vendorPackageMap() {
  const map = new Map();
  for (const name of readdirSync(join(vendorDir, 'packages')).sort()) {
    const pkgFile = join(vendorDir, 'packages', name, 'package.json');
    if (!existsSync(pkgFile)) continue;
    const pkg = readJson(pkgFile);
    for (const [key, target] of Object.entries(pkg.exports ?? {})) {
      if (typeof target !== 'string' || key.includes('*')) continue;
      const spec = pkg.name + (key === '.' ? '' : key.slice(1));
      map.set(spec, join(vendorDir, 'packages', name, target));
    }
  }
  return map;
}

function candidateFiles(base) {
  return [base, base + '.ts', base + '.tsx', join(base, 'index.ts'), join(base, 'index.tsx')];
}

function resolvePlugin({ catalog = null, external = [], overlayUi = false } = {}) {
  const packages = vendorPackageMap();
  const redirects = new Map(Object.entries(REDIRECTS).map(([from, to]) => [join(vendorDir, from), join(root, to)]));
  if (overlayUi) redirects.set(join(vendorDir, 'packages/ui/src/messaging.ts'), join(adapterDir, 'src/patches/overlay-messaging.ts'));
  const catalogFile = join(root, PROTECT_CATALOG_FILE);
  return {
    name: 'protect-production-resolve',
    setup(b) {
      // ADR-062: the disabled mode preview belongs to the inline Options section.
      // Keep the editable vendor form only while its Firewall feature actually runs.
      b.onLoad({ filter: /FirewallRulesPanel\.tsx$/ }, args => {
        if (args.path !== join(vendorDir, 'packages/ui/src/components/protect/firewall/FirewallRulesPanel.tsx')) return undefined;
        const source = lf(readFileSync(args.path, 'utf8'));
        const marker = '{running ? (\n        <form\n          class="fw-mode"';
        if (source.split(marker).length !== 2) throw new Error('inline Firewall mode adapter requires review');
        return { contents: source.replace(marker, marker.replace('{running ?', '{firewallOn ?')), loader: 'tsx', resolveDir: dirname(args.path) };
      });
      if (overlayUi) {
        b.onLoad({ filter: /FirewallCard\.tsx$/ }, args => {
          if (args.path !== join(vendorDir, 'packages/ui/src/components/protect/firewall/FirewallCard.tsx')) return undefined;
          const source = readFileSync(args.path, 'utf8');
          if (source.split('document.getElementById(').length !== 3) throw new Error('overlay FirewallCard focus adapter requires review');
          const client = join(adapterDir, 'src/overlay-client.ts').split(sep).join('/');
          return { contents: 'import { overlayElementById } from ' + JSON.stringify(client) + ';\n' + source.replaceAll('document.getElementById(', 'overlayElementById('), loader: 'tsx', resolveDir: dirname(args.path) };
        });
        b.onLoad({ filter: /overlay-styles\.ts$/ }, args => {
          if (args.path !== join(adapterDir, 'src/overlay-styles.ts')) return undefined;
          const css = [readFileSync(join(outDir, 'ui.css'), 'utf8'), readFileSync(join(outDir, 'button-surfaces.css'), 'utf8'), composeProtectCss({ overlayLast: true })].join('\n')
            .replace(/:root\s+body\b/g, '.protect-overlay-page')
            .replace(/:root\b|\bbody\b|\bhtml\b/g, '.protect-overlay-page');
          return { contents: 'export default ' + JSON.stringify(css) + ';', loader: 'js' };
        });
      }
      b.onResolve({ filter: /^@detect-expert\// }, (args) => {
        const target = packages.get(args.path);
        if (target === undefined) return { errors: [{ text: 'unknown vendored package import ' + args.path }] };
        return { path: target };
      });
      b.onResolve({ filter: /^\.{1,2}\// }, (args) => {
        if (external.includes(args.path)) return { path: args.path, external: true };
        const base = resolve(args.resolveDir, args.path);
        if (catalog !== null && base === catalogFile) return { path: catalogFile };
        for (const file of candidateFiles(base)) {
          const target = redirects.get(file);
          if (target !== undefined && args.importer !== target) return { path: target };
        }
        return undefined;
      });
      if (catalog !== null) {
        b.onLoad({ filter: /catalog\.generated\.json$/ }, (args) => {
          if (args.path !== catalogFile) return undefined;
          return { contents: JSON.stringify(catalog), loader: 'json' };
        });
      }
    },
  };
}

