/** Provenance of the inputs: vendored or adapter sources; Preact only in UI bundles; redirected files never. */
export function auditProvenance(bundle, inputs) {
  const problems = [];
  const preactDir = join(root, 'node_modules', '.pnpm', 'preact@' + PREACT_VERSION) + sep;
  for (const input of Object.keys(inputs)) {
    const file = inputFile(input);
    const inVendor = file.startsWith(vendorDir + sep);
    const inAdapter = file.startsWith(join(adapterDir, 'src') + sep);
    const inPreact = file.startsWith(preactDir);
    if (inPreact && bundle.world !== 'ui') problems.push('Preact in a ' + bundle.world + ' bundle: ' + rel(file));
    if (!inVendor && !inAdapter && !inPreact) problems.push('input outside vendor/protect-722fae8, apps/production-protect/src and Preact ' + PREACT_VERSION + ': ' + rel(file));
    if (inVendor) {
      const vrel = relative(vendorDir, file).split(sep).join('/');
      if (Object.hasOwn(REDIRECTS, vrel)) problems.push('redirected vendored file bundled: ' + vrel);
      if (bundle.testOnly !== true && /synthetic/.test(vrel)) problems.push('synthetic test data in a production bundle: ' + vrel);
    }
  }
  // 722fae8 auditInputs: no test, data or script inputs (test-only overlay bundles excepted); node_modules only in UI.
  for (const hit of auditInputs(inputs, bundle.world, { testOnly: bundle.testOnly === true })) problems.push(hit);
  return problems;
}

/** 722fae8 verifyBundle + code checks on the bundle text. */
export function auditBundle(bundle, text, { production = true } = {}) {
  const problems = [];
  if (bundle.format === 'iife') {
    if (/^\s*import\s/m.test(text)) problems.push('contains an import statement');
    if (/^\s*export\s/m.test(text)) problems.push('contains an export statement');
  } else {
    const imports = text.match(/^\s*import\s.*$/gm) ?? [];
    const allowed = (bundle.external ?? []).map((spec) => 'from "' + spec + '";');
    for (const line of imports) if (!allowed.some((a) => line.trim().endsWith(a))) problems.push('unexpected import: ' + line.trim().slice(0, 120));
  }
  if (/\brequire\s*\(/.test(text)) problems.push('contains require()');
  if (/\bimport\s*\(/.test(text)) problems.push('contains dynamic import()');
  if (/sourceMappingURL/.test(text)) problems.push('contains a sourcemap comment');
  if (bundle.world === 'main' && /\bchrome\./.test(text)) problems.push('MAIN bundle references chrome.*');
  if (bundle.prelude === true && Buffer.byteLength(text) > MAX_PRELUDE_BYTES) problems.push('prelude exceeds ' + MAX_PRELUDE_BYTES + ' B (' + String(Buffer.byteLength(text)) + ')');
  if (bundle.out === 'protect.js') {
    if (/\bchrome\s*\??\.\s*scripting\b/.test(text)) problems.push('references chrome.scripting');
    for (const hit of bundleOccurrencesOutside(text, /\bpostMessage\s*\(/, [PROTECT_RELAY_MODULE])) problems.push('postMessage( outside ' + PROTECT_RELAY_MODULE + ' (' + (hit.module || 'bundle prologue') + ', line ' + String(hit.line) + ')');
  }
  if (text.includes('extraHeaders')) problems.push('contains extraHeaders');
  if (production && (text.includes('protect-tripwire') || text.includes('__protectHarness'))) problems.push('production output contains protect-tripwire / __protectHarness');
  // 722fae8 scanCode: the MAIN hook table appears exactly once (protect.main.js); HTML sinks are allowed only in the UI
  // (Preact's implementation; the lint inventory pins that prefix).
  for (const hit of scanCode(text, bundle.out, { html: bundle.world !== 'ui', hookTargets: 1 })) problems.push(hit);
  return problems;
}

/** protect-ui.js: Preact first, then the marker; returns the sha256 of the prefix (what pnpm lint pins). */
export function preactPrefix(text) {
  const end = text.indexOf(PREACT_PREFIX_MARKER);
  if (end < 0) return { problems: ['marker "' + PREACT_PREFIX_MARKER + '" missing'], sha256: null };
  const prefix = text.slice(0, end);
  const problems = [];
  const modules = [...prefix.matchAll(/^\/\/ (\S+)$/gm)].map((m) => m[1]);
  if (modules.length === 0 || modules.some((m) => !m.startsWith('../../node_modules/.pnpm/preact@' + PREACT_VERSION + '/'))) problems.push('the prefix before ' + PREACT_PREFIX_MARKER + ' holds modules other than Preact ' + PREACT_VERSION + ': ' + modules.join(', '));
  return { problems, sha256: createHash('sha256').update(prefix).digest('hex') };
}

/** Adapter replacements retain the original source's ownership and single-reader checks. */
export function auditProtectSource(source, file) {
  const canonical = Object.entries(REDIRECTS).find(([, adapter]) => adapter === file)?.[0] ?? file;
  return [...scanFieldReads(source, canonical), ...scanApiOwnership(source, canonical)];
}

/** scanFieldReads + scanApiOwnership of 722fae8 over vendored production sources and the adapter sources. */
export function auditSources() {
  const problems = [];
  let files = 0;
  const visit = (dir, base, prefix) => {
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) {
        visit(full, base, prefix);
        continue;
      }
      if (!/\.(?:ts|tsx)$/.test(name) || name.endsWith('.d.ts')) continue;
      const r = prefix + relative(base, full).split(sep).join('/');
      if (!isProductionSource(r)) continue;
      files++;
      const source = readFileSync(full, 'utf8');
      for (const hit of auditProtectSource(source, r)) problems.push(r + ': ' + hit);
    }
  };
  for (const pkg of readdirSync(join(vendorDir, 'packages')).sort()) {
    const src = join(vendorDir, 'packages', pkg, 'src');
    if (existsSync(src)) visit(src, vendorDir, '');
  }
  visit(join(vendorDir, 'apps/extension/entrypoints'), vendorDir, '');
  visit(join(adapterDir, 'src'), root, '');
  return { problems, files };
}

function observationProblems() {
  const problems = [];
  for (const name of OBSERVATION_BUNDLES) {
    const file = join(outDir, name);
    if (!existsSync(file)) continue;
    const text = readFileSync(file, 'utf8');
    for (const marker of OBSERVATION_FORBIDDEN_STRINGS) if (text.includes(marker)) problems.push(name + ': observation bundle contains module string "' + marker + '"');
  }
  return problems;
}

function inventoryProblems(prefixSha) {
  const inventory = readJson(join(root, LINT_INVENTORY));
  const pinned = inventory.preact?.[PRODUCTION_EXTENSION_DIR + '/protect-ui.js'];
  if (pinned === prefixSha) return [];
  return [LINT_INVENTORY + ': preact["' + PRODUCTION_EXTENSION_DIR + '/protect-ui.js"] is ' + String(pinned) + ', the built Preact prefix hashes to ' + prefixSha + ' (independent dependency review, then pin it)'];
}

