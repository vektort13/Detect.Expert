/** Top-level CSS blocks: [{ prelude, body, text }], comments outside blocks dropped. */
function cssBlocks(css) {
  const blocks = [];
  let i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2);
      i = end < 0 ? css.length : end + 2;
      continue;
    }
    if (/\s/.test(css[i])) {
      i++;
      continue;
    }
    const open = css.indexOf('{', i);
    if (open < 0) break;
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css.startsWith('/*', j)) {
        const end = css.indexOf('*/', j + 2);
        j = end < 0 ? css.length : end + 1;
        continue;
      }
      if (css[j] === '{') depth++;
      else if (css[j] === '}') {
        depth--;
        if (depth === 0) break;
      }
    }
    blocks.push({ prelude: css.slice(i, open).trim(), body: css.slice(open + 1, j), text: css.slice(i, j + 1) });
    i = j + 1;
  }
  return blocks;
}

/** Rules of `css` whose selectors use one of the inherited classes (inside @media blocks too). */
export function inheritedRules(css) {
  const out = [];
  for (const block of cssBlocks(css)) {
    if (block.prelude.startsWith('@media') || block.prelude.startsWith('@supports')) {
      const inner = inheritedRules(block.body);
      if (inner.length > 0) out.push(block.prelude + ' {\n' + inner.map((r) => '  ' + r.replace(/\n/g, '\n  ')).join('\n') + '\n}');
    } else if (!block.prelude.startsWith('@') && INHERITED_UI_CLASSES.test(block.prelude)) out.push(block.text);
  }
  return out;
}

export function composeProtectCss({ overlayLast = false } = {}) {
  const vendorStyles = join(vendorDir, 'packages/ui/src/styles/protect');
  const names = readdirSync(vendorStyles).filter((n) => n.endsWith('.css')).sort();
  if (!names.includes('base.css')) throw new Error('vendored base.css of the module styles is missing');
  const parts = names.map((n) => '/* --- protect/' + n + ' (vendor) --- */\n' + lf(readFileSync(join(vendorStyles, n), 'utf8')).replace(/\n*$/, '\n'));
  const inherited = inheritedRules(lf(readFileSync(join(vendorDir, 'packages/ui/src/styles/ui.css'), 'utf8')));
  if (inherited.length === 0) throw new Error('no inherited ui.css rules found');
  parts.push('/* --- ui.css of 722fae8: classes the production ui.css lacks --- */\n' + inherited.join('\n\n') + '\n');
  const ownStyles = join(adapterDir, 'src/styles');
  const ownNames = readdirSync(ownStyles).filter((x) => x.endsWith('.css')).sort();
  if (overlayLast && ownNames.includes('overlay.css')) { ownNames.splice(ownNames.indexOf('overlay.css'), 1); ownNames.push('overlay.css'); }
  for (const n of ownNames) {
    parts.push('/* --- production/' + n + ' --- */\n' + lf(readFileSync(join(ownStyles, n), 'utf8')).replace(/\n*$/, '\n'));
  }
  return CSS_BANNER + parts.join('');
}

