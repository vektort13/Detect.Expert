export async function buildAll() {
  const problems = [];
  const vendor = checkVendor();
  if (vendor.problems.length > 0) return { problems: vendor.problems.map((p) => 'vendor: ' + p) };
  const groups = [...(await loadContractExport('protect.ts', 'PROTECT_MAIN_GROUPS'))];
  if (JSON.stringify(groups) !== JSON.stringify(PROTECT_GROUPS)) problems.push('PROTECT_MAIN_GROUPS of the vendored contracts ' + JSON.stringify(groups) + ' differ from protect-files.mjs ' + JSON.stringify(PROTECT_GROUPS));

  const files = new Map();
  const records = {};
  let catalogInfo = null;
  let prefixSha = null;
  for (const bundle of PROTECT_BUNDLES) {
    let result;
    if (bundle.catalog === true) {
      // Pass 1 finds the UI inputs (independent of the catalog contents), pass 2 embeds the catalog they need.
      const first = await runBuild(bundle, { catalog: { ru: {}, en: {} } });
      catalogInfo = composeCatalog(first.inputs);
      problems.push(...catalogInfo.problems);
      result = await runBuild(bundle, { catalog: catalogInfo.catalog });
      const prefix = preactPrefix(result.text);
      problems.push(...prefix.problems.map((p) => bundle.out + ': ' + p));
      prefixSha = prefix.sha256;
    } else {
      result = await runBuild(bundle);
    }
    for (const w of result.warnings) problems.push(bundle.out + ': esbuild warning: ' + w.text);
    problems.push(...auditProvenance(bundle, result.inputs).map((p) => bundle.out + ': ' + p));
    problems.push(...auditBundle(bundle, result.text).map((p) => bundle.out + ': ' + p));
    files.set(bundle.out, Buffer.from(result.text, 'utf8'));
    records[bundle.out] = { entry: bundle.entry, format: bundle.format, world: bundle.world, inputs: Object.keys(result.inputs).length };
  }
  for (const s of PROTECT_STATIC) files.set(s.out, readFileSync(join(root, s.from)));
  files.set(PROTECT_CSS, Buffer.from(composeProtectCss(), 'utf8'));
  if (catalogInfo !== null) files.set('catalog', Buffer.from(JSON.stringify(catalogInfo.catalog, null, 2) + '\n', 'utf8'));
  const sources = auditSources();
  problems.push(...sources.problems);
  problems.push(...observationProblems());
  if (prefixSha !== null) problems.push(...inventoryProblems(prefixSha));

  const outputs = {};
  for (const name of PROTECT_OUTPUTS) {
    const bytes = files.get(name);
    if (bytes === undefined) {
      problems.push('missing output ' + name);
      continue;
    }
    outputs[name] = { bytes: bytes.length, sha256: sha256(bytes), ...(records[name] ?? {}) };
  }
  const catalogBytes = files.get('catalog');
  const record = {
    schema: 1,
    adr: 'ADR-047',
    note: 'Provenance of the module «Защита» files in apps/production-extension; written by scripts/production/build-protect.mjs, verified by its --check.',
    commit: VENDOR_COMMIT,
    vendorManifestSha256: sha256(readFileSync(join(root, VENDOR_MANIFEST))),
    vendorTreeSha256: vendor.treeSha256,
    esbuild: esbuildVersion,
    preact: PREACT_VERSION,
    options: { bundle: true, minify: false, minifySyntax: true, treeShaking: true, target: ['chrome119'], charset: 'utf8', legalComments: 'none', jsx: 'automatic', jsxImportSource: 'preact', sourcemap: false },
    defines: { 'process.env.NODE_ENV': '"production"', __BUILD_PROFILE__: '"local"', __EARLY_CAPTURE__: 'false (true in protect.main.js)', __PROTECT_OVERLAY__: 'false' },
    redirects: REDIRECTS,
    hookConfig: 'apps/production-protect/src/hook-config.ts (owner decision 2026-10-18: listen off, send wrap, observe wrap, imgSrc off)',
    catalog: catalogInfo === null || catalogBytes === undefined ? null : { file: PROTECT_CATALOG_FILE, sha256: sha256(catalogBytes), vendorKeys: catalogInfo.vendorKeys, productionKeys: catalogInfo.ownKeys, overrides: catalogInfo.overrides, languages: ['ru', 'en'] },
    preactPrefixSha256: prefixSha,
    sourceAudit: { files: sources.files, gates: ['scanFieldReads', 'scanApiOwnership'] },
    outputs,
  };
  files.set('record', Buffer.from(JSON.stringify(record, null, 2) + '\n', 'utf8'));
  return { problems, files, record };
}

function targetPath(name) {
  if (name === 'record') return join(root, PROTECT_BUILD_RECORD);
  if (name === 'catalog') return join(root, PROTECT_CATALOG_FILE);
  return join(outDir, name);
}

async function overlay(dirArg) {
  const target = resolve(root, dirArg);
  if (target === root || target.startsWith(join(root, 'apps') + sep) || target === join(root, 'apps') || target.startsWith(join(root, 'vendor') + sep)) {
    throw new Error('--overlay writes test bundles only outside apps/ and vendor/ (got ' + rel(target) + ')');
  }
  const problems = [];
  const sw = PROTECT_BUNDLES.find((b) => b.out === 'protect-sw.js');
  const out = new Map();
  const swResult = await runBuild(sw, { define: { __PROTECT_OVERLAY__: 'true' } });
  problems.push(...auditProvenance(sw, swResult.inputs).map((p) => 'protect-sw.js (overlay): ' + p));
  problems.push(...auditBundle(sw, swResult.text, { production: false }).map((p) => 'protect-sw.js (overlay): ' + p));
  if (!swResult.text.includes('protect-tripwire.isolated.js')) problems.push('overlay protect-sw.js does not register the tripwire files');
  out.set('protect-sw.js', swResult.text);
  for (const bundle of PROTECT_OVERLAY_BUNDLES) {
    const result = await runBuild(bundle);
    problems.push(...auditProvenance(bundle, result.inputs).map((p) => bundle.out + ': ' + p));
    problems.push(...auditBundle(bundle, result.text, { production: false }).map((p) => bundle.out + ': ' + p));
    out.set(bundle.out, result.text);
  }
  if (problems.length > 0) return problems;
  mkdirSync(target, { recursive: true });
  for (const [name, text] of out) writeFileSync(join(target, name), text, 'utf8');
  console.log('build-protect: overlay -> ' + rel(target) + ' (' + [...out.keys()].join(', ') + ')');
  return [];
}

async function main(argv) {
  let check = false;
  let overlayDir = null;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') check = true;
    else if (argv[i] === '--overlay') {
      overlayDir = argv[++i];
      if (overlayDir === undefined) throw new Error('--overlay requires a directory');
    } else throw new Error('unknown argument ' + argv[i]);
  }
  if (overlayDir !== null) {
    const problems = await overlay(overlayDir);
    if (problems.length > 0) {
      for (const p of problems) console.error('build-protect: ' + p);
      process.exit(1);
    }
    return;
  }
  const { problems, files, record } = await buildAll();
  if (problems.length > 0) {
    for (const p of problems) console.error('build-protect: ' + p);
    process.exit(1);
  }
  if (check) {
    const stale = [];
    for (const [name, bytes] of files) {
      const file = targetPath(name);
      if (!existsSync(file) || !readFileSync(file).equals(bytes)) stale.push(rel(file));
    }
    if (stale.length > 0) {
      for (const s of stale) console.error('build-protect: stale or missing ' + s + ' (run node scripts/production/build-protect.mjs)');
      process.exit(1);
    }
    console.log('build-protect: OK (' + String(Object.keys(record.outputs).length) + ' module files, BUILD.json and the catalog match a fresh build of ' + VENDOR_COMMIT.slice(0, 7) + '; ' + String(record.sourceAudit.files) + ' sources audited)');
    return;
  }
  for (const [name, bytes] of files) {
    const file = targetPath(name);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, bytes);
  }
  console.log('build-protect: ' + String(Object.keys(record.outputs).length) + ' module files -> ' + PRODUCTION_EXTENSION_DIR + ' (commit ' + VENDOR_COMMIT.slice(0, 7) + ', esbuild ' + esbuildVersion + ')');
  for (const [name, o] of Object.entries(record.outputs)) console.log('  ' + name.padEnd(22) + String(o.bytes).padStart(9) + ' B  sha256 ' + o.sha256.slice(0, 16));
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    await main(process.argv.slice(2));
  } catch (error) {
    console.error('build-protect: ' + (error instanceof Error ? error.message : String(error)));
    process.exit(1);
  }
}
