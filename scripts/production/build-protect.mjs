function placeholdersOf(entry) {
  return JSON.stringify(Object.keys(entry.placeholders ?? {}).sort()) + '|' + JSON.stringify([...entry.message.matchAll(/\$([a-z_][a-z0-9_]*)\$/gi)].map((m) => m[1].toLowerCase()).sort());
}

/** String-literal keys and literal prefixes (`'fw_kind_' + x`, `` `fw_${x}` ``) of a source text. */
function literalKeys(source) {
  const keys = new Set();
  const prefixes = new Set();
  for (const m of source.matchAll(/(['"])([a-z][a-z0-9_]*)\1/g)) {
    if (m[2].endsWith('_')) prefixes.add(m[2]);
    else keys.add(m[2]);
  }
  for (const m of source.matchAll(/`([a-z][a-z0-9_]*_)\$\{/g)) prefixes.add(m[1]);
  return { keys, prefixes };
}

/** Consent texts (PROTECT_CONSENT_KEYS of 722fae8 all carry this prefix): never replaced by a production override. */
const CONSENT_KEY_PREFIX = 'protect_consent_';

/**
 * Production text overrides of vendored keys (apps/production-protect/src/locales/overrides.json, S3: owner decision
 * Q1 makes the DNR permission required, so the SP-1 restart texts change). Text only: an existing vendored key, never a
 * consent key, ru and en both, the same placeholders as the vendored entry.
 */
export function readOverrides(vendorRu, vendorEn) {
  const file = join(adapterDir, 'src/locales/overrides.json');
  const problems = [];
  const messages = existsSync(file) ? (readJson(file).messages ?? {}) : {};
  for (const [key, entry] of Object.entries(messages)) {
    if (!Object.hasOwn(vendorRu, key) || !Object.hasOwn(vendorEn, key)) problems.push('override of an unknown vendored key: ' + key);
    else if (key.startsWith(CONSENT_KEY_PREFIX)) problems.push('override of a consent key (digest of 722fae8): ' + key);
    else {
      for (const [lang, vendor] of [['ru', vendorRu], ['en', vendorEn]]) {
        if (typeof entry?.[lang] !== 'string' || entry[lang].length === 0) problems.push('override without ' + lang + ' text: ' + key);
        else if (placeholdersOf({ ...vendor[key], message: entry[lang] }) !== placeholdersOf(vendor[key])) problems.push('override changes the placeholders of ' + key + ' (' + lang + ')');
      }
    }
  }
  return { messages, problems };
}

/** ru/en catalog of the module: selected vendored keys + the production keys of apps/production-protect/src/locales. */
export function composeCatalog(uiInputs) {
  const vendorRu = readJson(join(vendorDir, 'apps/extension/_locales/ru/messages.json'));
  const vendorEn = readJson(join(vendorDir, 'apps/extension/_locales/en/messages.json'));
  const ownRu = readJson(join(adapterDir, 'src/locales/ru.json'));
  const ownEn = readJson(join(adapterDir, 'src/locales/en.json'));
  const overrides = readOverrides(vendorRu, vendorEn);
  const problems = [...overrides.problems];
  const sameKeys = (a, b) => JSON.stringify(Object.keys(a).sort()) === JSON.stringify(Object.keys(b).sort());
  if (!sameKeys(vendorRu, vendorEn)) problems.push('vendored ru/en catalogs differ in keys');
  if (!sameKeys(ownRu, ownEn)) problems.push('apps/production-protect/src/locales ru/en differ in keys');
  for (const key of Object.keys(ownRu)) {
    if (Object.hasOwn(vendorRu, key)) problems.push('production module key collides with a vendored key: ' + key);
    if (placeholdersOf(ownRu[key]) !== placeholdersOf(ownEn[key])) problems.push('placeholders differ between ru and en: ' + key);
  }
  const selected = new Set();
  const all = Object.keys(vendorRu);
  for (const key of all) if (CATALOG_PREFIXES.some((p) => key.startsWith(p)) || CATALOG_KEYS.includes(key)) selected.add(key);
  for (const input of Object.keys(uiInputs)) {
    const file = isAbsolute(input) ? input : resolve(vendorDir, input);
    if (!(file.startsWith(vendorDir + sep) || file.startsWith(join(adapterDir, 'src') + sep)) || !/\.(?:ts|tsx)$/.test(file)) continue;
    const { keys, prefixes } = literalKeys(readFileSync(file, 'utf8'));
    for (const key of keys) if (Object.hasOwn(vendorRu, key)) selected.add(key);
    for (const prefix of prefixes) for (const key of all) if (key.startsWith(prefix)) selected.add(key);
  }
  for (const key of Object.keys(overrides.messages)) if (!selected.has(key)) problems.push('override of a key the module catalog does not carry: ' + key);
  const pick = (vendor, own, lang) => {
    const out = {};
    for (const key of [...selected, ...Object.keys(own)].sort()) {
      const entry = Object.hasOwn(own, key) ? own[key] : vendor[key];
      const message = Object.hasOwn(overrides.messages, key) ? overrides.messages[key][lang] : entry.message;
      out[key] = entry.placeholders === undefined ? { message } : { message, placeholders: entry.placeholders };
    }
    return out;
  };
  const catalog = { ru: pick(vendorRu, ownRu, 'ru'), en: pick(vendorEn, ownEn, 'en') };
  for (const key of Object.keys(catalog.ru)) if (placeholdersOf(catalog.ru[key]) !== placeholdersOf(catalog.en[key])) problems.push('placeholders differ between ru and en: ' + key);
  return { catalog, problems, vendorKeys: selected.size, ownKeys: Object.keys(ownRu).length, overrides: Object.keys(overrides.messages).sort() };
}

