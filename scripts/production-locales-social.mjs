const COUNT_KEYS = new Set(['social_service_count', 'social_request_count']);

export function applySocialCopy(table, locale) {
  if (typeof locale !== 'string' || !Object.hasOwn(COPY, locale)) {
    throw new Error('Social copy: unknown locale ' + String(locale));
  }
  if (!table || typeof table !== 'object' || Array.isArray(table)) {
    throw new TypeError('Social copy: expected a message table');
  }
  const copy = COPY[locale];
  if (copy.length !== SOCIAL_COPY_KEYS.length || copy.some(message => typeof message !== 'string' || !message)) {
    throw new Error('Social copy: incomplete translations for ' + locale);
  }
  for (let index = 0; index < SOCIAL_COPY_KEYS.length; index++) {
    const key = SOCIAL_COPY_KEYS[index];
    const actual = [...copy[index].matchAll(/\$([A-Z][A-Z0-9_]*)\$/g)].map(match => match[1]);
    if (COUNT_KEYS.has(key) ? actual.length !== 1 || actual[0] !== 'COUNT' : actual.length !== 0) {
      throw new Error('Social copy: invalid placeholders for ' + locale + '/' + key);
    }
    table[key] = { message: copy[index] };
    if (COUNT_KEYS.has(key)) table[key].placeholders = { count: { content: '$1' } };
  }
  return table;
}
